    private sealed class ColorBox
    {
        public List<Color> Colors { get; }

        public ColorBox(List<Color> colors)
        {
            Colors = colors;
        }

        public int RangeR
        {
            get
            {
                if (Colors.Count == 0)
                    return 0;

                int min = 255;
                int max = 0;

                foreach (Color c in Colors)
                {
                    min = Math.Min(min, c.R);
                    max = Math.Max(max, c.R);
                }

                return max - min;
            }
        }

        public int RangeG
        {
            get
            {
                if (Colors.Count == 0)
                    return 0;

                int min = 255;
                int max = 0;

                foreach (Color c in Colors)
                {
                    min = Math.Min(min, c.G);
                    max = Math.Max(max, c.G);
                }

                return max - min;
            }
        }

        public int RangeB
        {
            get
            {
                if (Colors.Count == 0)
                    return 0;

                int min = 255;
                int max = 0;

                foreach (Color c in Colors)
                {
                    min = Math.Min(min, c.B);
                    max = Math.Max(max, c.B);
                }

                return max - min;
            }
        }

        public int LargestRange
        {
            get
            {
                return Math.Max(
                    RangeR,
                    Math.Max(RangeG, RangeB));
            }
        }
    }


    private static Color[] BuildPalette(
        Color[] pixels,
        int colorCount)
    {
        var boxes = new List<ColorBox>
        {
            new ColorBox(new List<Color>(pixels))
        };

        while (boxes.Count < colorCount)
        {
            ColorBox? boxToSplit = null;

            int largestRange = -1;

            foreach (ColorBox box in boxes)
            {
                if (box.Colors.Count <= 1)
                    continue;

                if (box.LargestRange > largestRange)
                {
                    largestRange = box.LargestRange;
                    boxToSplit = box;
                }
            }

            if (boxToSplit == null)
                break;

            ColorBox[] split = SplitBox(boxToSplit);

            boxes.Remove(boxToSplit);
            boxes.Add(split[0]);
            boxes.Add(split[1]);
        }

        var palette = new List<Color>();

        foreach (ColorBox box in boxes)
        {
            if (box.Colors.Count == 0)
                continue;

            long r = 0;
            long g = 0;
            long b = 0;

            foreach (Color c in box.Colors)
            {
                r += c.R;
                g += c.G;
                b += c.B;
            }

            int count = box.Colors.Count;

            palette.Add(
                Color.FromArgb(
                    (int)(r / count),
                    (int)(g / count),
                    (int)(b / count)));
        }

        return palette.ToArray();
    }


    private static ColorBox[] SplitBox(ColorBox box)
    {
        int rangeR = box.RangeR;
        int rangeG = box.RangeG;
        int rangeB = box.RangeB;

        if (rangeR >= rangeG && rangeR >= rangeB)
        {
            box.Colors.Sort((a, b) =>
                a.R.CompareTo(b.R));
        }
        else if (rangeG >= rangeR && rangeG >= rangeB)
        {
            box.Colors.Sort((a, b) =>
                a.G.CompareTo(b.G));
        }
        else
        {
            box.Colors.Sort((a, b) =>
                a.B.CompareTo(b.B));
        }

        int middle = box.Colors.Count / 2;

        List<Color> left =
            box.Colors.GetRange(
                0,
                middle);

        List<Color> right =
            box.Colors.GetRange(
                middle,
                box.Colors.Count - middle);

        return new[]
        {
            new ColorBox(left),
            new ColorBox(right)
        };
    }


    // ============================================================
    // MAP COLORS
    // ============================================================

        private static byte[] MapToPalette(
        Color[] pixels,
        Color[] palette,
        bool[] transparentMask,
        int transparentIndex)
    {
        byte[] indexes = new byte[pixels.Length];

        for (int i = 0; i < pixels.Length; i++)
        {
            if (transparentMask != null && i < transparentMask.Length && transparentMask[i])
            {
                indexes[i] = (byte)(transparentIndex >= 0 ? transparentIndex : 0);
            }
            else
            {
                indexes[i] =
                    (byte)FindNearestColor(
                        pixels[i],
                        palette);
            }
        }

        return indexes;
    }


    // ============================================================
    // FLOYD-STEINBERG DITHERING
    // ============================================================

        private static byte[] Dither(
        Color[] pixels,
        int width,
        int height,
        Color[] palette,
        bool[] transparentMask,
        int transparentIndex)
    {
        byte[] indexes = new byte[pixels.Length];

        float[] r = new float[pixels.Length];
        float[] g = new float[pixels.Length];
        float[] b = new float[pixels.Length];

        for (int i = 0; i < pixels.Length; i++)
        {
            r[i] = pixels[i].R;
            g[i] = pixels[i].G;
            b[i] = pixels[i].B;
        }

        for (int y = 0; y < height; y++)
        {
            bool reverse = (y & 1) != 0;

            int startX = reverse ? width - 1 : 0;
            int endX = reverse ? -1 : width;
            int step = reverse ? -1 : 1;

            for (int x = startX; x != endX; x += step)
            {
                int pixelIndex =
                    y * width + x;

                // If this pixel is marked transparent, assign transparent index and skip error diffusion
                if (transparentMask != null && pixelIndex < transparentMask.Length && transparentMask[pixelIndex])
                {
                    indexes[pixelIndex] = (byte)(transparentIndex >= 0 ? transparentIndex : 0);
                    continue;
                }

                Color current = Color.FromArgb(
                    ClampToByte(r[pixelIndex]),
                    ClampToByte(g[pixelIndex]),
                    ClampToByte(b[pixelIndex]));

                int paletteIndex =
                    FindNearestColor(
                        current,
                        palette);

                indexes[pixelIndex] =
                    (byte)paletteIndex;

                Color replacement =
                    palette[paletteIndex];

                float errorR =
                    r[pixelIndex] - replacement.R;

                float errorG =
                    g[pixelIndex] - replacement.G;

                float errorB =
                    b[pixelIndex] - replacement.B;

                if (!reverse)
                {
                    AddError(
                        r, g, b,
                        width,
                        height,
                        x + 1, y,
                        errorR,
                        errorG,
                        errorB,
                        7f / 16f);

                    AddError(
                        r, g, b,
                        width,
                        height,
                        x - 1, y + 1,
                        errorR,
                        errorG,
                        errorB,
                        3f / 16f);

                    AddError(
                        r, g, b,
                        width,
                        height,
                        x, y + 1,
                        errorR,
                        errorG,
                        errorB,
                        5f / 16f);

                    AddError(
                        r, g, b,
                        width,
                        height,
                        x + 1, y + 1,
                        errorR,
                        errorG,
                        errorB,
                        1f / 16f);
                }
                else
                {
                    AddError(
                        r, g, b,
                        width,
                        height,
                        x - 1, y,
                        errorR,
                        errorG,
                        errorB,
                        7f / 16f);

                    AddError(
                        r, g, b,
                        width,
                        height,
                        x + 1, y + 1,
                        errorR,
                        errorG,
                        errorB,
                        3f / 16f);

                    AddError(
                        r, g, b,
                        width,
                        height,
                        x, y + 1,
                        errorR,
                        errorG,
                        errorB,
                        5f / 16f);

                    AddError(
                        r, g, b,
                        width,
                        height,
                        x - 1, y + 1,
                        errorR,
                        errorG,
                        errorB,
                        1f / 16f);
                }
            }
        }

        return indexes;
    }


    private static void AddError(
        float[] r,
        float[] g,
        float[] b,
        int width,
        int height,
        int x,
        int y,
        float errorR,
        float errorG,
        float errorB,
        float factor)
    {
        if (x < 0 ||
            x >= width ||
            y < 0 ||
            y >= height)
        {
            return;
        }

        int index =
            y * width + x;

        r[index] += errorR * factor;
        g[index] += errorG * factor;
        b[index] += errorB * factor;
    }


    // ============================================================
    // FIND NEAREST COLOR
    // ============================================================

    private static int FindNearestColor(
        Color color,
        Color[] palette)
    {
        int bestIndex = 0;
        int bestDistance = int.MaxValue;

        for (int i = 0; i < palette.Length; i++)
        {
            int dr = color.R - palette[i].R;
            int dg = color.G - palette[i].G;
            int db = color.B - palette[i].B;

            // Weighted distance roughly matching human
            // sensitivity to green.
            int distance =
                dr * dr * 30 +
                dg * dg * 59 +
                db * db * 11;

            if (distance < bestDistance)
            {
                bestDistance = distance;
                bestIndex = i;
            }
        }

        return bestIndex;
    }


    // ============================================================
    // PACK INDEXES
    // ============================================================

    private static byte[] PackIndexes(
        byte[] indexes,
        int width,
        int height,
        ColorDepth colorDepth)
    {
        int bitsPerPixel = (int)colorDepth;

        int pixelsPerByte =
            8 / bitsPerPixel;

        int dataSize =
            (indexes.Length + pixelsPerByte - 1)
            / pixelsPerByte;

        byte[] data =
            new byte[dataSize];

        int mask =
            (1 << bitsPerPixel) - 1;

        for (int i = 0; i < indexes.Length; i++)
        {
            int byteIndex =
                i / pixelsPerByte;

            int position =
                i % pixelsPerByte;

            int shift =
                8 - bitsPerPixel * (position + 1);

            data[byteIndex] |=
                (byte)((indexes[i] & mask) << shift);
        }

        return data;
    }


    // ============================================================
    // RGB888 -> RGB565
    // ============================================================

    private static ushort ToRgb565(Color color)
    {
        return (ushort)(
            ((color.R & 0xF8) << 8) |
            ((color.G & 0xFC) << 3) |
            (color.B >> 3));
    }


    // ============================================================
    // GENERATED getPixel()
    // ============================================================

    private static void AppendGetPixelFunction(
        StringBuilder sb,
        string identifier,
        string macroName,
        bool useColor565,
        bool hasTransparency)
    {
        sb.AppendLine(
            $"static inline uint16_t {identifier}GetPixel(");
        sb.AppendLine(
            "    uint16_t x,");
        sb.AppendLine(
            "    uint16_t y)");
        sb.AppendLine("{");

        sb.AppendLine(
            $"    if (x >= {macroName}_WIDTH || " +
            $"y >= {macroName}_HEIGHT)");
        sb.AppendLine(
            "        return 0;");
        sb.AppendLine();

        sb.AppendLine(
            "    uint32_t pixelIndex = " +
            $"(uint32_t)y * {macroName}_WIDTH + x;");
        sb.AppendLine();

        sb.AppendLine(
            "    uint8_t paletteIndex;");
        sb.AppendLine();

        // --------------------------------------------------------
        // 1 BPP
        // --------------------------------------------------------

        sb.AppendLine(
            $"    #if {macroName}_BPP == 1");

        sb.AppendLine(
            "    uint32_t byteIndex = pixelIndex >> 3;");

        sb.AppendLine(
            "    uint8_t shift = 7 - (pixelIndex & 7);");

        sb.AppendLine(
            $"    paletteIndex = " +
            $"(pgm_read_byte(&{identifier}[byteIndex]) >> shift) & 0x01;");

        // --------------------------------------------------------
        // 2 BPP
        // --------------------------------------------------------

        sb.AppendLine(
            $"    #elif {macroName}_BPP == 2");

        sb.AppendLine(
            "    uint32_t byteIndex = pixelIndex >> 2;");

        sb.AppendLine(
            "    uint8_t shift = 6 - ((pixelIndex & 3) * 2);");

        sb.AppendLine(
            $"    paletteIndex = " +
            $"(pgm_read_byte(&{identifier}[byteIndex]) >> shift) & 0x03;");

        // --------------------------------------------------------
        // 4 BPP
        // --------------------------------------------------------

        sb.AppendLine(
            $"    #elif {macroName}_BPP == 4");

        sb.AppendLine(
            "    uint32_t byteIndex = pixelIndex >> 1;");

        sb.AppendLine(
            "    uint8_t shift = " +
            "(pixelIndex & 1) ? 0 : 4;");

        sb.AppendLine(
            $"    paletteIndex = " +
            $"(pgm_read_byte(&{identifier}[byteIndex]) >> shift) & 0x0F;");

        // --------------------------------------------------------
        // 8 BPP
        // --------------------------------------------------------

        sb.AppendLine(
            $"    #else");

        sb.AppendLine(
            $"    paletteIndex = " +
            $"pgm_read_byte(&{identifier}[pixelIndex]);");

        sb.AppendLine(
            $"    #endif");

        sb.AppendLine();

        // --------------------------------------------------------
        // TRANSPARENCY CHECK
        // --------------------------------------------------------
        if (hasTransparency)
        {
            sb.AppendLine(
                $"    if (paletteIndex == {macroName}_TRANSPARENT_INDEX)");
            sb.AppendLine(
                "        return 0xFFFF;");
            sb.AppendLine();
        }

        // --------------------------------------------------------
        // RGB565 PALETTE
        // --------------------------------------------------------

        if (useColor565)
        {
            sb.AppendLine(
                $"    return pgm_read_word(" +
                $"&{identifier}Palette[paletteIndex]);");
        }
        else
        {
            sb.AppendLine(
                $"    uint8_t r = " +
                $"pgm_read_byte(&{identifier}Palette[paletteIndex][0]);");

            sb.AppendLine(
                $"    uint8_t g = " +
                $"pgm_read_byte(&{identifier}Palette[paletteIndex][1]);");

            sb.AppendLine(
                $"    uint8_t b = " +
                $"pgm_read_byte(&{identifier}Palette[paletteIndex][2]);");

            sb.AppendLine();

            sb.AppendLine(
                "    return (uint16_t)(");

            sb.AppendLine(
                "        ((r & 0xF8) << 8) |");

            sb.AppendLine(
                "        ((g & 0xFC) << 3) |");

            sb.AppendLine(
                "        (b >> 3));");
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }


    // ============================================================
    // BYTE ARRAY OUTPUT
    // ============================================================

    private static void AppendByteArray(
        StringBuilder sb,
        byte[] data)
    {
        const int bytesPerLine = 16;

        for (int i = 0; i < data.Length; i++)
        {
            if (i % bytesPerLine == 0)
                sb.Append("    ");

            sb.Append($"0x{data[i]:X2}");

            if (i < data.Length - 1)
                sb.Append(", ");

            if ((i + 1) % bytesPerLine == 0)
                sb.AppendLine();
        }

        if (data.Length % bytesPerLine != 0)
            sb.AppendLine();
    }


    // ============================================================
    // IDENTIFIER
    // ============================================================

    private static string MakeIdentifier(string name)
    {
        var sb = new StringBuilder();

        foreach (char c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
                sb.Append(c);
            else
                sb.Append('_');
        }

        if (sb.Length == 0)
            sb.Append("image");

        if (char.IsDigit(sb[0]))
            sb.Insert(0, '_');

        return sb.ToString();
    }


    // ============================================================
    // CLAMP
    // ============================================================

    private static int ClampToByte(float value)
    {
        if (value < 0)
            return 0;

        if (value > 255)
            return 255;

        return (int)Math.Round(value);
    }
