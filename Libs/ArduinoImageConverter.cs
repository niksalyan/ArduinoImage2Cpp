    // ============================================================
    // COLOR DEPTH
    // ============================================================

    public enum ColorDepth
    {
        Bpp1 = 1,   // 2 colors
        Bpp2 = 2,   // 4 colors
        Bpp4 = 4,   // 16 colors
        Bpp8 = 8    // 256 colors
    }


    // ============================================================
    // RESULT
    // ============================================================

    public sealed class IndexedImage
    {
        public int Width { get; }
        public int Height { get; }
        public ColorDepth ColorDepth { get; }

        // Packed pixel indexes
        public byte[] Data { get; }

        // RGB palette
        public Color[] Palette { get; }

        // Transparent palette index (-1 = none)
        public int TransparentIndex { get; }

        public int ColorsCount => Palette.Length;

        public int BitsPerPixel => (int)ColorDepth;

        public IndexedImage(
            int width,
            int height,
            ColorDepth colorDepth,
            byte[] data,
            Color[] palette,
            int transparentIndex = -1)
        {
            Width = width;
            Height = height;
            ColorDepth = colorDepth;
            Data = data;
            Palette = palette;
            TransparentIndex = transparentIndex;
        }


        // ========================================================
        // ARDUINO CODE GENERATION
        // ========================================================

        public string ToArduinoCode(DataModel data)
        {
            if (string.IsNullOrWhiteSpace(data.Output.Name))
                throw new ArgumentException("Name cannot be empty.", nameof(data.Output.Name));

            string identifier = MakeIdentifier(data.Output.Name);
            string macroName = identifier.ToUpperInvariant();

            var sb = new StringBuilder();

            sb.AppendLine("// ============================================================");
            sb.AppendLine($"// Generated by ArduinoImageConverter - {macroName}");
            sb.AppendLine("// ============================================================");
            sb.AppendLine();

            sb.AppendLine($"#define {macroName}_WIDTH       {Width}");
            sb.AppendLine($"#define {macroName}_HEIGHT      {Height}");
            sb.AppendLine($"#define {macroName}_BPP         {BitsPerPixel}");
            sb.AppendLine($"#define {macroName}_COLORS      {ColorsCount}");
            sb.AppendLine($"#define {macroName}_DATA_SIZE   {Data.Length}");
            sb.AppendLine();

            // ----------------------------------------------------
            // PIXEL DATA
            // ----------------------------------------------------

            sb.AppendLine($"const uint8_t {identifier}[] PROGMEM =");
            sb.AppendLine("{");

            AppendByteArray(sb, Data);

            sb.AppendLine("};");
            sb.AppendLine();

            // ----------------------------------------------------
            // PALETTE
            // ----------------------------------------------------

            if (data.Output.UseColor565)
            {
                sb.AppendLine(
                    $"const uint16_t {identifier}Palette[{ColorsCount}] PROGMEM =");
                sb.AppendLine("{");

                for (int i = 0; i < Palette.Length; i++)
                {
                    ushort rgb565 = ToRgb565(Palette[i]);

                    sb.Append($"    0x{rgb565:X4}");

                    if (i < Palette.Length - 1)
                        sb.Append(",");

                    sb.AppendLine();
                }

                sb.AppendLine("};");
            }
            else
            {
                sb.AppendLine(
                    $"const uint8_t {identifier}Palette[{ColorsCount}][3] PROGMEM =");
                sb.AppendLine("{");

                for (int i = 0; i < Palette.Length; i++)
                {
                    Color c = Palette[i];

                    sb.AppendLine(
                        $"    {{ {c.R}, {c.G}, {c.B} }}" +
                        (i < Palette.Length - 1 ? "," : ""));
                }

                sb.AppendLine("};");
            }

            sb.AppendLine();

            // ----------------------------------------------------
            // TRANSPARENCY
            // ----------------------------------------------------
            bool hasTransparency = TransparentIndex >= 0 && this.TransparentIndex < Palette.Length;
            if (hasTransparency)
            {
                sb.AppendLine($"#define {macroName}_TRANSPARENT_INDEX   {this.TransparentIndex}");
                sb.AppendLine();
            }

            // ----------------------------------------------------
            // GET PIXEL
            // ----------------------------------------------------

            if (data.Output.IncludeRenderFunction)
            {
                AppendGetPixelFunction(
                    sb,
                    identifier,
                    macroName,
                    data.Output.UseColor565,
                    hasTransparency);
            }

            return sb.ToString();
        }

        public Bitmap ToBitmap()
        {
            return ToBitmap(preview: false);
        }

        public Bitmap ToBitmap(bool preview = false)
        {
            int bitsPerPixel = BitsPerPixel;
            int pixelsPerByte = 8 / bitsPerPixel;
            int mask = (1 << bitsPerPixel) - 1;

            bool hasTransparency = TransparentIndex >= 0;

            // Build foreground buffer as 32bpp ARGB (non-premultiplied) in memory
            int fgStride = Width * 4;
            byte[] fgBuffer = new byte[fgStride * Height];

            for (int i = 0; i < Width * Height; i++)
            {
                int byteIndex = i / pixelsPerByte;
                int position = i % pixelsPerByte;
                int shift = 8 - bitsPerPixel * (position + 1);

                int paletteIndex = (Data[byteIndex] >> shift) & mask;

                int x = i % Width;
                int y = i / Width;

                int off = y * fgStride + x * 4;

                if (hasTransparency && paletteIndex == TransparentIndex)
                {
                    // Fully transparent pixel: all bytes zero
                    fgBuffer[off + 0] = 0;
                    fgBuffer[off + 1] = 0;
                    fgBuffer[off + 2] = 0;
                    fgBuffer[off + 3] = 0;
                }
                else
                {
                    Color color = Palette[paletteIndex];
                    fgBuffer[off + 0] = color.B;
                    fgBuffer[off + 1] = color.G;
                    fgBuffer[off + 2] = color.R;
                    fgBuffer[off + 3] = 255;
                }
            }

            // If non-preview, return a 32bpp bitmap constructed from fgBuffer
            if (!preview)
            {
                var fg = new Bitmap(Width, Height, PixelFormat.Format32bppArgb);
                var bd = fg.LockBits(new Rectangle(0, 0, Width, Height), ImageLockMode.WriteOnly, PixelFormat.Format32bppArgb);
                try
                {
                    Marshal.Copy(fgBuffer, 0, bd.Scan0, fgBuffer.Length);
                }
                finally
                {
                    fg.UnlockBits(bd);
                }

                return fg;
            }

            // Preview: build 24bpp checkerboard then copy opaque pixels from fgBuffer
            var previewBmp = new Bitmap(Width, Height, PixelFormat.Format24bppRgb);

            int cell = 8;
            Color c1 = Color.FromArgb(220, 220, 220);
            Color c2 = Color.FromArgb(180, 180, 180);

            int pbStride = ((Width * 3 + 3) / 4) * 4;
            byte[] pbBuffer = new byte[pbStride * Height];

            // Fill checkerboard
            for (int y = 0; y < Height; y++)
            {
                for (int x = 0; x < Width; x++)
                {
                    bool odd = ((x / cell) + (y / cell)) % 2 == 1;
                    Color baseColor = odd ? c1 : c2;

                    int off = y * pbStride + x * 3;
                    pbBuffer[off + 0] = baseColor.B;
                    pbBuffer[off + 1] = baseColor.G;
                    pbBuffer[off + 2] = baseColor.R;
                }
            }

            // Copy opaque pixels from fgBuffer to pbBuffer
            for (int y = 0; y < Height; y++)
            {
                for (int x = 0; x < Width; x++)
                {
                    int i = y * Width + x;
                    int foff = y * fgStride + x * 4;

                    byte a = fgBuffer[foff + 3];
                    if (a == 0)
                        continue;

                    int pbOff = y * pbStride + x * 3;
                    pbBuffer[pbOff + 0] = fgBuffer[foff + 0];
                    pbBuffer[pbOff + 1] = fgBuffer[foff + 1];
                    pbBuffer[pbOff + 2] = fgBuffer[foff + 2];
                }
            }

            var bd2 = previewBmp.LockBits(new Rectangle(0, 0, Width, Height), ImageLockMode.WriteOnly, PixelFormat.Format24bppRgb);
            try
            {
                Marshal.Copy(pbBuffer, 0, bd2.Scan0, pbBuffer.Length);
            }
            finally
            {
                previewBmp.UnlockBits(bd2);
            }

            return previewBmp;
        }

    }


    // ============================================================
    // PUBLIC CONVERSION FUNCTION
    // ============================================================

    public static IndexedImage Convert(DataModel data)
    {
        if (data == null)
            throw new ArgumentNullException(nameof(data));
        if (data.Image == null)
            throw new ArgumentNullException(nameof(data.Image));

        if (data.Input.Resize.Width <= 0)
            throw new ArgumentOutOfRangeException(nameof(data.Input.Resize.Width));


        if (data.Input.Resize.Height <= 0)
            throw new ArgumentOutOfRangeException(nameof(data.Input.Resize.Height));

        int colorsCount = GetColorsCount(data.Output.Palette);

        using Bitmap resized = GetImage(data);    

        // Read pixels including alpha channel so transparent source pixels are detected
        Color[] pixels = GetPixels(resized);

        // --------------------------------------------------
        // Handle transparent color + tolerance (Euclidean) and source alpha
        // - Support TransparentFromTopLeft: take effective transparent color from top-left pixel
        // - Treat any pixel with alpha < 255 as transparent (mask)
        // --------------------------------------------------
        Color effectiveTransparentColor = data.Output.TransparentColor;
        if (data.Output.TransparentFromTopLeft && effectiveTransparentColor.IsEmpty && pixels.Length > 0)
        {
            // top-left pixel after resize/crop
            effectiveTransparentColor = pixels[0];
        }

        // Detect any source alpha transparency
        bool hasAlphaTransparency = false;
        for (int i = 0; i < pixels.Length; i++)
        {
            if (pixels[i].A < 255)
            {
                hasAlphaTransparency = true;
                break;
            }
        }

        bool hasTransparentColor = !effectiveTransparentColor.IsEmpty || hasAlphaTransparency;

        bool[] transparentMask = new bool[pixels.Length];

        // First mark pixels that are transparent due to source alpha
        if (hasAlphaTransparency)
        {
            for (int i = 0; i < pixels.Length; i++)
            {
                transparentMask[i] = pixels[i].A < 190;
            }
        }

        // Then also mark pixels that match the transparent color within tolerance
        if (!effectiveTransparentColor.IsEmpty)
        {
            int tol = Math.Max(0, data.Output.TransparentTolerance);
            long tol2 = (long)tol * (long)tol;

            Color tc = effectiveTransparentColor;

            for (int i = 0; i < pixels.Length; i++)
            {
                int dr = pixels[i].R - tc.R;
                int dg = pixels[i].G - tc.G;
                int db = pixels[i].B - tc.B;

                long dist2 = (long)dr * dr + (long)dg * dg + (long)db * db;

                if (dist2 <= tol2)
                    transparentMask[i] = true;
            }
        }

        // Build palette excluding transparent pixels when appropriate
        Color[] palette;

        int maxPaletteSlots = GetColorsCount(data.Output.Palette);
        int maxColorsAllowed = (int)Math.Min(maxPaletteSlots, data.Input.MaxColors);

        if (hasTransparentColor)
        {
            var list = new List<Color>(pixels.Length);

            for (int i = 0; i < pixels.Length; i++)
            {
                if (!transparentMask[i])
                    list.Add(pixels[i]);
            }

            if (list.Count == 0)
            {
                // all pixels transparent: start with an empty palette
                palette = new Color[0];
            }
            else
            {
                // reserve one slot for the transparent color
                int paletteSlotsForColors = Math.Max(0, maxColorsAllowed - 1);
                if (paletteSlotsForColors <= 0)
                {
                    // no room for colors except the transparent one
                    palette = new Color[0];
                }
                else
                {
                    palette = BuildPalette(
                        list.ToArray(),
                        paletteSlotsForColors);
                }
            }
        }
        else
        {
            palette = BuildPalette(
                pixels,
                maxColorsAllowed);
        }

        // Build final palette list: if transparency requested, put transparent color at palette[0]
        var palList = new List<Color>();
        int computedTransparentIndex = -1;

        if (hasTransparentColor)
        {
            // Determine representative RGB for transparent pixels
            Color tc = effectiveTransparentColor;
            if (tc.IsEmpty && hasAlphaTransparency)
            {
                long sr = 0, sg = 0, sb = 0;
                int scount = 0;
                for (int i = 0; i < pixels.Length; i++)
                {
                    if (transparentMask[i])
                    {
                        sr += pixels[i].R;
                        sg += pixels[i].G;
                        sb += pixels[i].B;
                        scount++;
                    }
                }

                if (scount > 0)
                {
                    tc = Color.FromArgb((int)(sr / scount), (int)(sg / scount), (int)(sb / scount));
                }
                else if (pixels.Length > 0)
                {
                    tc = pixels[0];
                }
            }

            // Ensure transparent color occupies palette index 0
            palList.Add(Color.FromArgb(tc.R, tc.G, tc.B));
            computedTransparentIndex = 0;

            // Append computed palette colors (from non-transparent pixels) up to remaining slots
            int remainingSlots = Math.Max(0, maxPaletteSlots - 1);
            for (int i = 0; i < palette.Length && palList.Count < 1 + remainingSlots; i++)
            {
                palList.Add(palette[i]);
            }

            // Append include colors if space remains
            for (int i = 0; i < data.Palette.IncludeColors.Count && palList.Count < maxPaletteSlots; i++)
            {
                palList.Add(data.Palette.IncludeColors[i]);
            }
        }
        else
        {
            // No transparency: start with computed palette and append include colors
            palList.AddRange(palette);
            for (int i = 0; i < data.Palette.IncludeColors.Count && palList.Count < maxPaletteSlots; i++)
            {
                palList.Add(data.Palette.IncludeColors[i]);
            }
        }

        palette = palList.ToArray();

        byte[] indexes;

        if (data.Input.Dithering)
        {
            indexes = Dither(
                pixels,
                data.Input.Resize.Width,
                data.Input.Resize.Height,
                palette,
                transparentMask,
                computedTransparentIndex);
        }
        else
        {
            indexes = MapToPalette(
                pixels,
                palette,
                transparentMask,
                computedTransparentIndex);
        }

        // Apply transparent index to masked pixels (override mapped indexes)
        if (hasTransparentColor && computedTransparentIndex >= 0)
        {
            for (int i = 0; i < pixels.Length; i++)
            {
                if (transparentMask[i])
                    indexes[i] = (byte)computedTransparentIndex;
            }
        }

        byte[] packedData = PackIndexes(
            indexes,
            data.Input.Resize.Width,
            data.Input.Resize.Height,
            data.Output.Palette);

        int finalTransparentIndex = (hasTransparentColor && computedTransparentIndex >= 0)
            ? computedTransparentIndex
            : -1;

        return new IndexedImage(
            data.Input.Resize.Width,
            data.Input.Resize.Height,
            data.Output.Palette,
            packedData,
            palette,
            finalTransparentIndex);
    }


    // ============================================================
    // COLOR COUNT
    // ============================================================

    private static int GetColorsCount(ColorDepth depth)
    {
        return depth switch
        {
            ColorDepth.Bpp1 => 2,
            ColorDepth.Bpp2 => 4,
            ColorDepth.Bpp4 => 16,
            ColorDepth.Bpp8 => 256,

            _ => throw new ArgumentOutOfRangeException(nameof(depth))
        };
    }


    // ============================================================
    // RESIZE
    // ============================================================

        private static Bitmap GetImage(DataModel input)
        {
        // Use 32bpp with alpha to preserve source transparency through crop/resize
        Bitmap result = new Bitmap(
            input.Input.Resize.Width,
            input.Input.Resize.Height,
            PixelFormat.Format32bppArgb);

        using Graphics g = Graphics.FromImage(result);
        g.CompositingMode = CompositingMode.SourceOver;
        // Start fully transparent
        g.Clear(Color.Transparent);

        if (input.Input.Bicubic)
        {
            g.InterpolationMode = InterpolationMode.Bicubic;
            g.PixelOffsetMode = PixelOffsetMode.HighQuality;
            g.SmoothingMode = SmoothingMode.HighQuality;
            g.CompositingQuality = CompositingQuality.HighQuality;
        } else
        {
            g.InterpolationMode = InterpolationMode.Low;
            g.PixelOffsetMode = PixelOffsetMode.None;
            g.SmoothingMode = SmoothingMode.None;
            g.CompositingQuality = CompositingQuality.AssumeLinear;
        }
        
        var p = input.Input.Crop; // Padding
        bool cropEnabled = (p.Left + p.Top + p.Right + p.Bottom) > 0;
        if (cropEnabled)
        {
            // compute source rect from padding
            int srcX = p.Left;
            int srcY = p.Top;
            int srcW = input.Image.Width - p.Left - p.Right;
            int srcH = input.Image.Height - p.Top - p.Bottom;

            if (srcX < 0) srcX = 0;
            if (srcY < 0) srcY = 0;
            if (srcW < 0) srcW = 0;
            if (srcH < 0) srcH = 0;

            if (srcW > 0 && srcH > 0 && srcX < input.Image.Width && srcY < input.Image.Height)
            {
                var srcRect = new Rectangle(srcX, srcY, srcW, srcH);

                g.DrawImage(
                    input.Image,
                    new Rectangle(0, 0, input.Input.Resize.Width, input.Input.Resize.Height),
                    srcRect,
                    GraphicsUnit.Pixel);
            }
            else
            {
                // nothing to draw when padding excludes entire image
            }
        }
        else
        {
                // Draw image preserving alpha
                g.DrawImage(
                input.Image,
                new Rectangle(0, 0, input.Input.Resize.Width, input.Input.Resize.Height));
        }
        

        input.Filters.Apply(result);

        return result;
    }


    // ============================================================
    // GET PIXELS
    // ============================================================

    private static Color[] GetPixels(Bitmap bitmap)
    {
        Color[] pixels = new Color[
            bitmap.Width * bitmap.Height];

        int index = 0;

        for (int y = 0; y < bitmap.Height; y++)
        {
            for (int x = 0; x < bitmap.Width; x++)
            {
                pixels[index++] = bitmap.GetPixel(x, y);
            }
        }

        return pixels;
    }


